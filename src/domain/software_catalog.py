def get_software_by_name(name: str) -> dict[str, Any] | None:
    """Récupère un logiciel par son nom."""
    for software in DEFAULT_SOFTWARE_CATALOG:
        if software["name"] == name:
            return software
    return None


def get_software_by_category(category: str) -> list[dict[str, Any]]:
    """Récupère tous les logiciels d'une catégorie."""
    return [s for s in DEFAULT_SOFTWARE_CATALOG if s.get("category") == category]


def get_profile_packages(profile_name: str) -> list[str]:
    """Récupère la liste des packages d'un profil."""
    profile = SOFTWARE_PROFILES.get(profile_name)
    if profile:
        return profile.get("packages", [])
    return []


def get_featured_software() -> list[dict[str, Any]]:
    """Récupère les logiciels mis en avant."""
    return [s for s in DEFAULT_SOFTWARE_CATALOG if s.get("is_featured")]


def get_all_categories() -> list[str]:
    """Récupère toutes les catégories disponibles."""
    return list(CATEGORY_INFO.keys())


def get_install_command(software: dict[str, Any]) -> str:
    """Génère la commande d'installation pour un logiciel."""
    manager = software.get("package_manager", "chocolatey")
    package_id = software.get("package_id", software["name"])
    
    if manager == "chocolatey":
        return f"choco install {package_id} -y"
    elif manager == "windows_feature":
        return f"Install-WindowsFeature -Name {package_id} -IncludeManagementTools"
    elif manager == "windows_capability":
        return f"Add-WindowsCapability -Online -Name {package_id}"
    elif software.get("install_command_windows"):
        return software["install_command_windows"]
    else:
        return f"choco install {package_id} -y"
